interface CustomerLocalizationContextValue {
  locale: CustomerLocaleCode;
  config: CustomerLocalizationConfig;
  languages: typeof CUSTOMER_LOCALES;
  catalog: typeof GLOBAL_LANGUAGE_REGISTRY;
  setLanguage: (locale: CustomerLocaleCode) => Promise<void>;
  t: (key: string) => string;
}

const CustomerLocalizationContext = createContext<CustomerLocalizationContextValue>({
  locale: "en",
  config: DEFAULT_CUSTOMER_LOCALIZATION,
  languages: CUSTOMER_LOCALES,
  catalog: GLOBAL_LANGUAGE_REGISTRY,
  setLanguage: async () => {},
  t: (key) => key,
});

function websiteUidFromPath(pathname: string): string | null {
  return pathname.match(/^\/(?:banking|app|invest|forex|crypto)\/([^/]+)/)?.[1] ?? null;
}

function storedCustomer() {
  for (const key of CUSTOMER_STORAGE_KEYS) {
    try {
      const value = JSON.parse(localStorage.getItem(key) ?? "null");
      if (value) return value as { country?: string; preferredLocale?: string };
    } catch {
      // Ignore malformed stale local storage; the server remains authoritative.
    }
  }
  return null;
}

export function CustomerLocalizationProvider({ children }: { children: React.ReactNode }) {
  const [location] = useLocation();
  const websiteUid = websiteUidFromPath(location);
  const [manualLocale, setManualLocale] = useState<CustomerLocaleCode | null>(() => {
    if (typeof window === "undefined") return null;
    const uid = websiteUidFromPath(window.location.pathname);
    const stored = uid ? localStorage.getItem(`${LOCALE_STORAGE_PREFIX}${uid}`) : null;
    return isCustomerLocale(stored) ? stored : null;
  });
  const { data: site } = useQuery({
    queryKey: ["customer-localization-info", websiteUid],
    queryFn: () => publicInfo(websiteUid!),
    enabled: !!websiteUid,
    retry: false,
  });

  const config = useMemo(
    () => normalizeCustomerLocalization((site as any)?.localization),
    [(site as any)?.localization],
  );
  const customer = typeof window !== "undefined" ? storedCustomer() : null;
  const locale = resolveCustomerLocale(config, manualLocale ?? customer?.preferredLocale, customer?.country);

  useEffect(() => {
    if (!websiteUid) return;
    const stored = localStorage.getItem(`${LOCALE_STORAGE_PREFIX}${websiteUid}`);
    setManualLocale(isCustomerLocale(stored) ? stored : null);
  }, [websiteUid]);

  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === "ar" ? "rtl" : "ltr";
  }, [locale]);

  const setLanguage = async (next: CustomerLocaleCode) => {
    if (!config.supportedLocales.includes(next)) return;
    if (websiteUid) localStorage.setItem(`${LOCALE_STORAGE_PREFIX}${websiteUid}`, next);
    setManualLocale(next);
    const token = CUSTOMER_STORAGE_KEYS.map((key) => localStorage.getItem(key)).find(Boolean);
    if (token) {
      await fetch("/api/customer/preferences/language", {
        method: "PATCH",
        headers: {
          "Content-Type": "application/json",
          Authorization: `Bearer ${localStorage.getItem("danzy_banking_token") ?? localStorage.getItem("danzy_invest_token") ?? localStorage.getItem("danzy_forex_token") ?? localStorage.getItem("danzy_crypto_token") ?? ""}`,
        },
        body: JSON.stringify({ preferredLocale: next }),
      });
    }
  };

  return (
    <CustomerLocalizationContext.Provider value={{
      locale,
      config,
      languages: CUSTOMER_LOCALES,
      catalog: GLOBAL_LANGUAGE_REGISTRY,
      setLanguage,
      t: (key) => translations[locale]?.[key] ?? translations.en[key] ?? key,
    }}>
      {children}
    </CustomerLocalizationContext.Provider>
  );
}

export function useCustomerLocalization() {
  return useContext(CustomerLocalizationContext);
}