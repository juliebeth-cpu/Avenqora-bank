import { useQuery } from "@tanstack/react-query";
import { Link } from "wouter";
import { publicInfo } from "@/lib/portal-api";
import { ArrowLeft, Shield } from "lucide-react";
import { PublicSiteFooter } from "@/pages/public/site-info";
import { TrackingPrivacyContent } from "@/pages/public/tracking-content";
import { getPublicLegalProfile } from "@/pages/public/legal-content";

interface Props { params: { websiteUid: string } }

export default function PrivacyPage({ params }: Props) {
  const { websiteUid } = params;

  const { data: site } = useQuery({
    queryKey: ["public-info", websiteUid],
    queryFn: () => publicInfo(websiteUid),
    retry: false,
  });

  const siteName = site?.name ?? "Our Platform";
  const contactEmail = site?.companyEmail ?? site?.supportEmail ?? "privacy@platform.com";
  const companyAddress = site?.companyAddress ?? "";
  const launchDate = site?.launchDate ?? new Date().getFullYear().toString();
  const primary = site?.primaryColor ?? "#2563eb";
  const isTrackingWebsite = site?.type === "tracking";
  const legalProfile = getPublicLegalProfile(site);

  return (
    <div className="min-h-screen bg-[#06090f] text-white">
      {/* Header */}
      <header className="border-b border-white/[0.07] sticky top-0 z-50 backdrop-blur-md bg-[#06090f]/90">
        <div className="max-w-4xl mx-auto px-4 sm:px-6 h-16 flex items-center gap-4">
          <Link
            href={`/site/${websiteUid}`}
            className="flex items-center gap-2 text-slate-400 hover:text-white transition-colors text-sm"
          >
            <ArrowLeft className="w-4 h-4" />
            Back to {siteName}
          </Link>
        </div>
      </header>

      {/* Content */}
      <main className="max-w-4xl mx-auto px-4 sm:px-6 py-14">
        {/* Title */}
        <div className="mb-10">
          <div className="flex items-center gap-3 mb-4">
            <div className="w-10 h-10 rounded-xl flex items-center justify-center" style={{ backgroundColor: primary + "22" }}>
              <Shield className="w-5 h-5" style={{ color: primary }} />
            </div>
            <div>
              <h1 className="text-3xl font-bold text-white">Privacy Policy</h1>
              <p className="text-slate-400 text-sm mt-0.5">{siteName} — Effective as of {launchDate}</p>
            </div>
          </div>
          <p className="text-slate-400 text-sm leading-relaxed mt-4">
            {isTrackingWebsite
              ? `At ${siteName}, we are committed to protecting the information used to provide shipment visibility and customer support. This Privacy Policy explains how tracking, contact, and technical information is handled.`
              : `At ${siteName}, we are committed to protecting your personal information and your right to privacy. ${legalProfile.introduction} Please read this policy carefully.`}
          </p>
        </div>

        {isTrackingWebsite ? (
          <TrackingPrivacyContent
            siteName={siteName}
            contactEmail={contactEmail}
            companyAddress={companyAddress}
            primary={primary}
          />
        ) : (
          <div className="space-y-10 text-slate-300 text-sm leading-relaxed">

          {/* 1 */}
          <section>
            <h2 className="text-lg font-semibold text-white mb-3">1. Information We Collect</h2>
            <p className="mb-3">Depending on the services you use, we collect information that you provide directly to us or that is generated by your use of the website, including:</p>
            <ul className="list-disc list-inside space-y-1.5 text-slate-400 ml-2">
              {legalProfile.collectedInformation.map((item) => <li key={item}>{item}</li>)}
            </ul>
          </section>

          {/* 2 */}
          <section>
            <h2 className="text-lg font-semibold text-white mb-3">2. How We Use Your Information</h2>
            <p className="mb-3">We use the information we collect to:</p>
            <ul className="list-disc list-inside space-y-1.5 text-slate-400 ml-2">
              {legalProfile.usePurposes.map((item) => <li key={item}>{item}</li>)}
              <li>Comply with legal obligations and enforce our Terms and Conditions</li>
            </ul>
          </section>

          {/* 3 */}
          <section>
            <h2 className="text-lg font-semibold text-white mb-3">3. Legal Basis for Processing</h2>
            <p className="mb-3">We process your personal data on the following legal grounds:</p>
            <ul className="list-disc list-inside space-y-1.5 text-slate-400 ml-2">
              {legalProfile.legalBases.map((item) => <li key={item}>{item}</li>)}
            </ul>
          </section>

          {/* 4 */}
          <section>
            <h2 className="text-lg font-semibold text-white mb-3">4. How We Share Your Information</h2>
            <p className="mb-3">
              We do not sell, trade, or rent your personal information to third parties. We may share your information only in the following circumstances:
            </p>
            <ul className="list-disc list-inside space-y-1.5 text-slate-400 ml-2">
              <li><strong className="text-slate-300">Service Providers:</strong> Trusted third-party vendors who assist in operating our Platform, subject to confidentiality obligations</li>
              <li><strong className="text-slate-300">Legal Requirements:</strong> When required by law, court order, or governmental authority</li>
              <li><strong className="text-slate-300">Fraud Prevention:</strong> With law enforcement or fraud prevention agencies to protect against illegal activities</li>
              <li><strong className="text-slate-300">Business Transfers:</strong> In connection with a merger, acquisition, or sale of assets, with appropriate notice</li>
              <li><strong className="text-slate-300">Consent:</strong> With your explicit consent in any other case</li>
            </ul>
          </section>

          {/* 5 */}
          <section>
            <h2 className="text-lg font-semibold text-white mb-3">5. Data Retention</h2>
            <p>{legalProfile.retention} When data is no longer required, it is securely deleted or anonymized where appropriate.</p>
          </section>

          {/* 6 */}
          <section>
            <h2 className="text-lg font-semibold text-white mb-3">6. Data Security</h2>
            <p>
              We implement industry-standard security measures to protect your personal information against unauthorized access,
              alteration, disclosure, or destruction. These measures include SSL/TLS encryption, bcrypt password hashing,
              secure token-based authentication, and regular security audits. However, no method of transmission over the
              internet or electronic storage is 100% secure, and we cannot guarantee absolute security.
            </p>
          </section>

          {/* 7 */}
          <section>
            <h2 className="text-lg font-semibold text-white mb-3">7. Cookies &amp; Tracking Technologies</h2>
            <p>
              We use cookies and similar tracking technologies to track activity on our Platform and hold certain information.
              Cookies are files with a small amount of data that may include an anonymous unique identifier. You can instruct
              your browser to refuse all cookies or to indicate when a cookie is being sent. However, if you do not accept
              cookies, you may not be able to use some portions of our Platform.
            </p>
          </section>

          {/* 8 */}
          <section>
            <h2 className="text-lg font-semibold text-white mb-3">8. Your Rights</h2>
            <p className="mb-3">Depending on your jurisdiction, you may have the following rights regarding your personal data:</p>
            <ul className="list-disc list-inside space-y-1.5 text-slate-400 ml-2">
              <li><strong className="text-slate-300">Access:</strong> The right to request a copy of the personal data we hold about you</li>
              <li><strong className="text-slate-300">Rectification:</strong> The right to request correction of inaccurate or incomplete data</li>
              <li><strong className="text-slate-300">Erasure:</strong> The right to request deletion of your data, subject to legal retention obligations</li>
              <li><strong className="text-slate-300">Restriction:</strong> The right to request that we restrict processing of your data</li>
              <li><strong className="text-slate-300">Data Portability:</strong> The right to receive your data in a structured, machine-readable format</li>
              <li><strong className="text-slate-300">Objection:</strong> The right to object to certain types of processing</li>
              <li><strong className="text-slate-300">Withdraw Consent:</strong> The right to withdraw consent at any time where processing is based on consent</li>
            </ul>
            <p className="mt-3">To exercise these rights, please contact us using the details below.</p>
          </section>

          {/* 9 */}
          <section>
            <h2 className="text-lg font-semibold text-white mb-3">9. Children's Privacy</h2>
            <p>{legalProfile.childrenPrivacy} If you believe information was provided contrary to this policy, please contact us so we can review it.</p>
          </section>

          {/* 10 */}
          <section>
            <h2 className="text-lg font-semibold text-white mb-3">10. Third-Party Links</h2>
            <p>
              Our Platform may contain links to third-party websites. We are not responsible for the privacy practices of
              those sites and encourage you to review their privacy policies. This Privacy Policy applies only to information
              collected by {siteName}.
            </p>
          </section>

          {/* 11 */}
          <section>
            <h2 className="text-lg font-semibold text-white mb-3">11. Changes to This Policy</h2>
            <p>
              We may update this Privacy Policy from time to time. We will notify you of any significant changes by posting
              the new Privacy Policy on this page and updating the effective date. We encourage you to review this Privacy
              Policy periodically. Your continued use of the Platform after changes are posted constitutes your acceptance
              of the revised policy.
            </p>
          </section>

          {/* 12 */}
          <section>
            <h2 className="text-lg font-semibold text-white mb-3">12. Contact Us</h2>
            <p className="mb-3">
              If you have questions about this Privacy Policy, wish to exercise your rights, or have concerns about how
              we handle your data, please contact our Data Protection Officer:
            </p>
            <div className="bg-white/[0.04] border border-white/[0.08] rounded-xl p-5 space-y-1.5">
              <p className="font-semibold text-white">{siteName} — Data Protection</p>
              {contactEmail && <p className="text-slate-400">Email: <a href={`mailto:${contactEmail}`} className="underline hover:text-white" style={{ color: primary }}>{contactEmail}</a></p>}
              {companyAddress && <p className="text-slate-400">Address: {companyAddress}</p>}
            </div>
          </section>
          </div>
        )}

        {/* Bottom nav */}
        <div className="mt-14 pt-8 border-t border-white/[0.07] flex flex-col sm:flex-row items-center justify-between gap-4">
          <Link
            href={`/site/${websiteUid}`}
            className="inline-flex items-center gap-2 text-sm text-slate-400 hover:text-white transition-colors"
          >
            <ArrowLeft className="w-4 h-4" />
            Back to {siteName}
          </Link>
          <Link
            href={`/site/${websiteUid}/terms`}
            className="text-sm hover:text-white transition-colors"
            style={{ color: primary }}
          >
            Terms &amp; Conditions →
          </Link>
        </div>
      </main>

      <PublicSiteFooter
        siteName={siteName}
        websiteUid={websiteUid}
        primary={primary}
        websiteType={site?.type}
        description={`Privacy information for ${siteName}.`}
      />
    </div>
  );
}
